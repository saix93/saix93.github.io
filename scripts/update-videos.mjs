// Regenerates videos-list.js with the whitelisted videos of the channel's Videos tab and keeps
// img/videos/ in sync: downloads the thumbnail of every new video and deletes the rest.
// Channel videos missing from videos-whitelist.txt are added to it commented out, ready to whitelist.
// Run with `node scripts/update-videos.mjs` (Node 18+). The GitHub Action runs it daily.
import { readFile, writeFile, readdir, unlink, mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const CHANNEL = 'https://www.youtube.com/@rtorresgonzalez93/videos';
const ROOT = fileURLToPath(new URL('..', import.meta.url));
const THUMBS = join(ROOT, 'img/videos');
const HEADERS = { 'User-Agent': 'Mozilla/5.0', 'Accept-Language': 'en' };

// Finds every video card and the "load more" token anywhere in a YouTube data blob.
function collect(data, videos) {
  let token = null;
  (function walk(o) {
    if (!o || typeof o !== 'object') return;
    if (o.lockupViewModel) {
      const v = o.lockupViewModel;
      const duration = (JSON.stringify(v.contentImage || {}).match(/"text":"(\d+(?::\d\d)+)"/) || [])[1] || '';
      const title = v.metadata?.lockupMetadataViewModel?.title?.content;
      if (v.contentId && title) videos.push({ id: v.contentId, title, duration });
      return;
    }
    // The token that loads more videos sits at the end of the list of video cards.
    if (Array.isArray(o) && o.some(i => i?.richItemRenderer)) {
      const more = o.find(i => i?.continuationItemRenderer);
      if (more) token = more.continuationItemRenderer.continuationEndpoint?.continuationCommand?.token || null;
    }
    for (const k in o) walk(o[k]);
  })(data);
  return token;
}

async function fetchVideos() {
  const html = await (await fetch(CHANNEL, { headers: HEADERS })).text();
  const initial = html.match(/var ytInitialData = (\{.*?\});<\/script>/s);
  const version = html.match(/"INNERTUBE_CLIENT_VERSION":"([^"]+)"/);
  if (!initial || !version) throw new Error('Could not read the channel page');

  const videos = [];
  let token = collect(JSON.parse(initial[1]), videos);
  while (token) {
    const res = await fetch('https://www.youtube.com/youtubei/v1/browse?prettyPrint=false', {
      method: 'POST',
      headers: { ...HEADERS, 'Content-Type': 'application/json' },
      body: JSON.stringify({ context: { client: { clientName: 'WEB', clientVersion: version[1], hl: 'en' } }, continuation: token })
    });
    token = collect(await res.json(), videos);
  }
  return videos;
}

// sddefault (640x480) and hqdefault (480x360) are 16:9 frames letterboxed in 4:3;
// the cards crop them to 16:9 with object-fit: cover, which drops the bars exactly.
async function downloadThumb(id) {
  for (const size of ['sddefault', 'hqdefault']) {
    const res = await fetch(`https://i.ytimg.com/vi/${id}/${size}.jpg`);
    if (res.ok) return writeFile(join(THUMBS, id + '.jpg'), Buffer.from(await res.arrayBuffer()));
  }
  throw new Error('No thumbnail for ' + id);
}

const channel = await fetchVideos();
if (!channel.length) throw new Error('No videos found, leaving everything as it was');

// Whitelist: one video ID per line, # starts a comment. A commented-out ID is known but hidden.
const WHITELIST = join(ROOT, 'scripts/videos-whitelist.txt');
const lines = (await readFile(WHITELIST, 'utf8').catch(() => '')).split(/\r?\n/);
const shown = new Set(lines.map(l => l.replace(/#.*/, '').trim()).filter(Boolean));
const known = new Set(lines.map(l => (l.match(/^[#\s]*([\w-]{11})\b/) || [])[1]).filter(Boolean));
const added = channel.filter(v => !known.has(v.id));
if (added.length) {
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  await writeFile(WHITELIST, lines.concat(added.map(v => '# ' + v.id + '   # ' + v.title)).join('\n') + '\n');
}
const videos = channel.filter(v => shown.has(v.id));

await mkdir(THUMBS, { recursive: true });
for (const v of videos) if (!existsSync(join(THUMBS, v.id + '.jpg'))) await downloadThumb(v.id);
const keep = new Set(videos.map(v => v.id + '.jpg'));
for (const file of await readdir(THUMBS)) if (!keep.has(file)) await unlink(join(THUMBS, file));

await writeFile(join(ROOT, 'videos-list.js'),
  '// Generated by scripts/update-videos.mjs from the YouTube channel. Don\'t edit by hand.\n' +
  'window.VIDEOS = [\n' + videos.map(v => '  ' + JSON.stringify(v)).join(',\n') + '\n];\n');
console.log(videos.length + ' of ' + channel.length + ' videos shown, ' + added.length + ' new in the whitelist');
